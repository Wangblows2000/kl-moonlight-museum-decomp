"""Account for every code entry point that no NATURAL run has executed -> docs/unexecuted.md.

Each one gets a category, decided from evidence (in this order):
  unreferenced        dead code: no caller, jump, table entry or vector install (hints/notes)
  dead-caller-only    every caller is unreferenced code
  data-unreachable    reachable by code, but the shipped data never selects it (e.g. a sound
                      command byte that occurs in no sequence; checked against gamedata/)
  state-unreachable   belongs to game states 14/15, which no instruction ever enters
  forced-only         executed, but only in forced (fault-injection / fixture) runs
  object-not-seen     object type never present in any natural run (objtypes.txt)
  pair-not-seen       collision callback whose two object types never met in a natural run
  coverage            reachable with shipped data; not yet exercised by natural play
Inputs: build/functions.json, build/trace.json, build/runtime_coverage.json, build/runtime/*,
gamedata/sound/seq (for sequence command usage)."""
import glob, json, os, re
from collections import Counter, defaultdict
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
J = lambda *p: json.load(open(os.path.join(ROOT, *p)))
funcs = J('build', 'functions.json')
T = J('build', 'trace.json')
cov = J('build', 'runtime_coverage.json')
xrefs = {int(k): v for k, v in T['xrefs'].items()}
dead = set(T.get('dead_insn', []))
nat = set(int(x, 16) for x in cov.get('entry_points_executed_natural_list', []))
anyx = set(int(x, 16) for x in cov['entry_points_executed_list'])

# object types seen in natural runs (per-frame slot types in frames.csv)
types_nat, pairs_nat = set(), set()
for d in glob.glob(os.path.join(ROOT, 'build', 'runtime', '*')):
    sp = os.path.join(d, 'summary.json')
    if not os.path.exists(sp) or json.load(open(sp)).get('provenance') != 'natural':
        continue
    for line in open(os.path.join(d, 'frames.csv')):
        if line[0] in 'f#':
            continue
        ts = {int(t) for t in line.split(',')[4].split() if t != '0'}
        types_nat |= ts
        pairs_nat |= {(a, b) for a in ts for b in ts}

# sequence commands used by the shipped sound data
SEQ_CMD = {'snd_cmd_loop_a': 'loop', 'snd_cmd_loop_a_alt': 'loop_alt', 'snd_cmd_loop_b': 'loopb',
           'snd_cmd_loop_b_alt': 'loopb_alt', 'snd_cmd_play_sound': 'play'}
used_cmds = Counter()
for f in glob.glob(os.path.join(ROOT, 'gamedata', 'sound', 'seq', '*.txt')):
    for line in open(f):
        w = line.split(';')[0].split()
        if w:
            used_cmds[w[0]] += 1

rows = []
for f in funcs:
    h = int(f['file'], 16)
    if h in nat:
        continue
    name = f['name']
    callers = [c for c in xrefs.get(h, [])]
    ev = ''
    if f['basis'] == 'dead' or name.startswith('unused_') or h in dead:
        cat, ev = 'unreferenced', 'no caller, jump, table entry or vector install; never executed in any run'
    elif callers and all(c in dead for c in callers):
        cat, ev = 'dead-caller-only', 'only called from unreferenced code (%s)' % ', '.join('%05X' % c for c in callers[:4])
    elif name in SEQ_CMD and used_cmds[SEQ_CMD[name]] == 0:
        cat, ev = 'data-unreachable', 'sequence command `%s` occurs in none of the 106 shipped sound scripts' % SEQ_CMD[name]
    elif name.startswith(('state14', 'state15')):
        cat, ev = 'state-unreachable', 'game states 14/15 are never written by any instruction (docs/game-states.md)'
    elif h in anyx:
        cat, ev = 'forced-only', 'executed only in forced runs (fault injection or unlock fixture)'
    else:
        m = re.match(r'coll_([0-9a-f]{2})_([0-9a-f]{2})', name, re.I)
        o = re.match(r'obj([0-9a-f]{2})_', name, re.I)
        if m and (int(m.group(1), 16), int(m.group(2), 16)) not in pairs_nat:
            a, b = int(m.group(1), 16), int(m.group(2), 16)
            seen = [t for t in (a, b) if t in types_nat]
            cat, ev = 'pair-not-seen', 'object types %02Xh and %02Xh never on screen together in a natural run (seen alone: %s)' % (
                a, b, ', '.join('%02Xh' % t for t in seen) or 'neither')
        elif o and int(o.group(1), 16) not in types_nat:
            cat, ev = 'object-not-seen', 'object type %sh never present in a natural run' % o.group(1).upper()
        else:
            cat, ev = 'coverage', 'reachable with the shipped data; the condition that selects it was not met in natural play'
    rows.append(dict(addr=f['addr'], name=name, category=cat, evidence=ev, size=f['size'], summary=f.get('summary', '')))

cnt = Counter(r['category'] for r in rows)
L = ['# Code not executed in natural play', '',
     'Generated by `tools/unexecuted.py` from the natural runs (controller input only, replayed from',
     'power-on).  Every entry point not executed naturally is listed with the reason established',
     'for it; only `unreferenced`, `dead-caller-only`, `data-unreachable` and `state-unreachable`',
     'are shown to be impossible in the shipped game.  The rest is a coverage gap.', '',
     '| category | entry points |', '|---|---:|']
for k, v in sorted(cnt.items()):
    L.append('| %s | %d |' % (k, v))
L += ['', '| address | name | category | evidence |', '|---|---|---|---|']
for r in sorted(rows, key=lambda r: (r['category'], r['addr'])):
    L.append('| %s | `%s` | %s | %s |' % (r['addr'], r['name'], r['category'], r['evidence']))
open(os.path.join(ROOT, 'docs', 'unexecuted.md'), 'w').write('\n'.join(L) + '\n')
json.dump({'note': __doc__.strip(), 'counts': dict(cnt), 'routines': rows},
          open(os.path.join(ROOT, 'docs', 'unexecuted.json'), 'w'), indent=1)
print(dict(cnt))
