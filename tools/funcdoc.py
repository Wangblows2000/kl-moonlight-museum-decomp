"""Generate docs/functions.md and build/functions.json: one row per code entry point.

Naming basis:  hand  = named after reading the routine (symbols.py, with confidence tag)
               role  = name states a proven dispatch role (tools/roles.py), behaviour not yet described
               none  = generic sub_XXXX / h_XXXX
Runtime: 'yes' if the instruction at the entry executed in any emulator run under build/runtime."""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
sys.path.insert(0, HERE)
import symbols as SYM
import hints

# reviewed descriptions of dead (unreferenced) code ranges, keyed by every byte of the range
DEADDOC = {}
for _r in hints.bank4_notes():
    if _r['kind'] == 'dead_code':
        for _i in range(int(_r['start'], 16), int(_r['end'], 16)):
            DEADDOC[_i] = _r

T = json.load(open(os.path.join(ROOT, 'build', 'trace.json')))
F = json.load(open(os.path.join(ROOT, 'build', 'funcs.json')))
R = json.load(open(os.path.join(ROOT, 'build', 'roles.json')))
_rd = os.path.join(ROOT, 'tools', 'routine_docs.json')
RD = json.load(open(_rd)) if os.path.exists(_rd) else {}
covp = os.path.join(ROOT, 'build', 'runtime_coverage.json')
executed = set(json.load(open(covp))['entry_points_executed_list']) if os.path.exists(covp) else set()
rows = []
for k, v in sorted(F.items(), key=lambda kv: int(kv[0])):
    f = int(k); off = f - 0x40000
    if off in SYM.NAMES:
        name, basis = SYM.NAMES[off], 'hand'
        m = re.search(r'\[(high|medium)\]', SYM.COMMENTS.get(off, ''))
        conf = m.group(1) if m else 'medium'
    elif RD.get('%04X' % off, {}).get('confidence') in ('high', 'medium'):
        name = RD['%04X' % off].get('name') or R.get('%04X' % off, {}).get('name') or 'sub_%04X' % off
        basis, conf = 'reviewed', RD['%04X' % off]['confidence']
    elif v['kind'] == ['dead']:
        name, basis, conf = 'dead_%04X' % off, 'dead', DEADDOC[f]['confidence'] if f in DEADDOC else '-'
    elif '%04X' % off in R:
        name, basis, conf = R['%04X' % off]['name'], 'role', 'role'
    else:
        name, basis, conf = ('sub_%04X' if v['callers'] and set(v['kind']) & {'call', 'farcall'} else 'h_%04X') % off, 'none', '-'
    summ = RD.get('%04X' % off, {}).get('summary') or ''
    if not summ and basis == 'dead' and f in DEADDOC:
        d = DEADDOC[f]
        summ = 'Unreferenced (range %s-%s): %s' % (d['start'], d['end'], d['format'])
    rows.append(dict(summary=summ, addr='4000:%04X' % off, file='%05X' % f, name=name, basis=basis, confidence=conf,
                     kind=v['kind'], size=v['size'], callers=v['callers'],
                     callees=['%04X' % c for c in v['calls']], ports_out=v['out'], ports_in=v['inp'], segments=v['segs'],
                     roles=R.get('%04X' % off, {}).get('roles', []), runtime_executed='%05X' % f in executed))
json.dump(rows, open(os.path.join(ROOT, 'build', 'functions.json'), 'w'), indent=0)
from collections import Counter
c = Counter(r['basis'] for r in rows)
L = ['# Code entry points', '',
     'Generated by `tools/funcdoc.py`.  %d entry points: %d named after reading the code (hand), '
     '%d named by proven dispatch role (role), %d still generic (none), %d unreferenced dead code (dead).  '
     '%d were executed in at least one emulator run.' % (len(rows), c['hand'], c['role'], c['none'], c['dead'],
                                                          sum(r['runtime_executed'] for r in rows)), '',
     '*reviewed* = behaviour documented from a full read of the routine (tools/routine_docs.json, with '
     'summary, registers, side effects and evidence in the asm header comment); confidence high/medium.', '',
     'A *role* name (e.g. `obj1C_update`, `coll_01_23`) says how the routine is reached, not what it does; '
     'its behaviour still needs documenting.  See docs/STATUS.md for the naming-confidence rules.', '',
     '| address | name | basis | conf | size | callers | out ports | in ports | segs | ran | summary |',
     '|---|---|---|---|---:|---:|---|---|---|---|---|']
for r in rows:
    L.append('| %s | `%s` | %s | %s | %d | %d | %s | %s | %s | %s | %s |' % (
        r['addr'], r['name'], r['basis'], r['confidence'], r['size'], r['callers'],
        ' '.join(p.replace('0x', '') for p in r['ports_out']), ' '.join(p.replace('0x', '') for p in r['ports_in']),
        ' '.join(r['segments']), 'yes' if r['runtime_executed'] else '', r['summary'].replace('|', '/')[:160]))
open(os.path.join(ROOT, 'docs', 'functions.md'), 'w').write('\n'.join(L) + '\n')
print(dict(c), 'executed', sum(r['runtime_executed'] for r in rows), 'of', len(rows))
